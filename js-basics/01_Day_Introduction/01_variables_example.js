// ===== DAY 1: INTRODUCTION - VARIABLES =====
// Learning: How to declare and use variables in JavaScript

// 1. Declaring variables with let
let firstName = 'John';
let lastName = 'Doe';
let country = 'USA';
let city = 'New York';
let age = 25;

console.log('--- Variables Example ---');
console.log('First Name:', firstName);
console.log('Last Name:', lastName);
console.log('Country:', country);
console.log('City:', city);
console.log('Age:', age);

// 2. Declaring constants with const (cannot be changed)
const gravity = 9.81;      // Earth's gravity in m/s²
const boilingPoint = 100;  // Water's boiling point in °C
const PI = 3.14159;        // Pi constant

console.log('\n--- Constants ---');
console.log('Gravity:', gravity);
console.log('Boiling Point:', boilingPoint);
console.log('Pi:', PI);

// 3. Multiple variable declaration
let language = 'JavaScript',
    job = 'Developer',
    experience = 3;

console.log('\n--- Multiple Declarations ---');
console.log('Language:', language);
console.log('Job:', job);
console.log('Experience:', experience, 'years');
